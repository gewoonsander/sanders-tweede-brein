// CONTRACT for every other locale.
//
// `TranslationKey = keyof typeof en`, so:
//   * `t('foo.bar')` with an unknown key is a COMPILE error, not a blank span.
//   * nl.ts is typed `Record<TranslationKey, string>` — a missing or misspelled
//     Dutch key is a COMPILE error too. The runtime English fallback in
//     i18n/index.ts is belt-and-braces, not the primary safety net.
//
